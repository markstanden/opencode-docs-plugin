// Isolation and blinding at the real launch boundaries.
//
// The real container wrapper and judge runner run against a fake podman and a
// fake judge launcher. The trial container must see only its own runtime and
// case, and a stamp in judge-bound text must stop dispatch.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
    chmodSync,
    existsSync,
    mkdirSync,
    mkdtempSync,
    readFileSync,
    readdirSync,
    symlinkSync,
    writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join } from "node:path";
import { describe, it } from "node:test";
import { fileURLToPath } from "node:url";
import { buildAcPrompt } from "./fixtures/placement-harness/ac-scoring.mts";

const HERE = dirname(fileURLToPath(import.meta.url));
const HARNESS = join(HERE, "fixtures/placement-harness");
const CORPUS = join(HARNESS, "prod014/cases.json");
const RUNNER = join(HARNESS, "ac/run.mjs");
const sha256 = (text) =>
    createHash("sha256").update(text, "utf8").digest("hex");

/** A temp campaign with R01 generated by the real host harness. */
function trialStage() {
    const root = mkdtempSync(join(tmpdir(), "pd-isolation-"));
    for (const dir of ["prompts", "fixtures", "rubrics", "results", "run-fixtures"]) {
        mkdirSync(join(root, dir), { recursive: true });
    }
    execFileSync(
        process.execPath,
        [
            join(HARNESS, "harness.mts"),
            "generate",
            "R01",
            "--fixture",
            CORPUS,
            "--prompts",
            join(root, "prompts"),
            "--fixtures",
            join(root, "fixtures"),
            "--rubrics",
            join(root, "rubrics"),
        ],
        { stdio: "ignore" },
    );
    const capture = join(root, "podman-capture.txt");
    const binary = join(root, "podman");
    writeFileSync(
        binary,
        `#!/usr/bin/env bash
printf '%s\\n' "$*" >>"$CAPTURE"
if [ "$1" = image ] && [ "$2" = inspect ]; then printf 'sha256:fakeid\\n'; fi
exit 0
`,
    );
    chmodSync(binary, 0o755);
    return { root, binary, capture };
}

/** The host paths mounted by the recorded podman run. */
function mountedSources(capturePath) {
    const lines = readFileSync(capturePath, "utf8").trim().split("\n");
    const run = lines.find((line) => line.startsWith("run "));
    assert.ok(run, "no container run was recorded");
    const words = run.split(" ");
    const sources = [];
    for (let index = 0; index < words.length; index += 1) {
        if (words[index] === "-v") sources.push(words[index + 1].split(":")[0]);
    }
    return sources;
}

describe("trial isolation", () => {
    it("mounts only the runtime and the selected case", () => {
        // Arrange
        const stage = trialStage();
        const env = {
            ...process.env,
            PATH: `${stage.root}:${process.env.PATH ?? ""}`,
            CAPTURE: stage.capture,
            PLACEMENT_CASES: CORPUS,
            PLACEMENT_PROMPTS: join(stage.root, "prompts"),
            PLACEMENT_FIXTURES: join(stage.root, "fixtures"),
            PLACEMENT_RUBRICS: join(stage.root, "rubrics"),
            PLACEMENT_RESULTS: join(stage.root, "results"),
            PLACEMENT_RUN_FIXTURES: join(stage.root, "run-fixtures"),
            TRIAL_TIMEOUT_MS: "1000",
        };

        // Act
        const result = spawnSync(
            join(HARNESS, "container-run.sh"),
            ["run", "R01", "--stamp", "iso"],
            { env, encoding: "utf8" },
        );

        // Assert
        assert.equal(result.status, 0, result.stderr);
        const sources = mountedSources(stage.capture);
        for (const source of sources) {
            assert.ok(
                source !== HARNESS && !source.startsWith(`${HARNESS}/`),
                `the full harness directory is mounted: ${source}`,
            );
        }
        const runtime = sources.find((source) =>
            basename(source).startsWith("harness-runtime-"),
        );
        assert.ok(runtime, "no staged runtime was mounted");
        const runtimeFiles = [];
        const walk = (dir, prefix = "") => {
            for (const entry of readdirSync(dir, { withFileTypes: true })) {
                const path = join(dir, entry.name);
                const name = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
                if (entry.isDirectory()) walk(path, name);
                else runtimeFiles.push(name);
            }
        };
        walk(runtime);
        assert.deepEqual(runtimeFiles.sort(), [
            "analysis/journal.ts",
            "harness.mts",
            "primary-checks/R01.mjs",
            "primary-checks/_replication-shared.mjs",
            "scenario-names.mts",
        ]);
        const corpusMount = sources.find((source) =>
            source.endsWith("cases-selected-R01.json"),
        );
        assert.ok(corpusMount, "no per-case corpus was mounted");
        const selected = JSON.parse(readFileSync(corpusMount, "utf8"));
        assert.deepEqual(
            selected.map((entry) => entry.id),
            ["R01"],
        );
        assert.ok(!runtimeFiles.includes("prod014/truth.json"));
    });
});

/** A minimal recorded trial for one judge dispatch. */
function judgeStage(answer, meta = { answerHash: sha256(answer) }) {
    const root = mkdtempSync(join(tmpdir(), "pd-judge-"));
    const stamp = "pd-A-r0-S02";
    const caseId = "S02";
    const caseDir = join(root, "results", stamp, caseId);
    mkdirSync(join(caseDir, "live/lakes"), { recursive: true });
    mkdirSync(join(root, "fixtures", caseId, "work"), { recursive: true });
    writeFileSync(
        join(root, "fixtures", caseId, "work/AGENTS.md"),
        "You may record durable findings.\n",
    );
    writeFileSync(join(caseDir, "meta.json"), JSON.stringify(meta));
    writeFileSync(join(caseDir, "final.md"), answer);
    writeFileSync(join(caseDir, "prompt.md"), "Repair the check.\n");
    writeFileSync(join(caseDir, "writes.txt"), "none\n");
    writeFileSync(join(caseDir, "primary-check.json"), JSON.stringify({ status: "pass" }));
    writeFileSync(join(root, "truth.json"), JSON.stringify({ [caseId]: "A truth." }));
    writeFileSync(join(root, "spec.json"), JSON.stringify({ scenarios: {} }));
    const launch = join(root, "launch.json");
    const launcher = join(root, "judge.sh");
    writeFileSync(
        launcher,
        `#!/usr/bin/env bash
node -e 'const fs=require("fs");const v={cwd:process.cwd(),pwd:process.env.PWD,args:process.argv.slice(1),key:process.env.ZAI_API_KEY??null};fs.writeFileSync(process.env.LAUNCH_CAPTURE,JSON.stringify(v))' "$@"
printf '%s\\n' '{"type":"text","part":{"type":"text","text":"{\\"documentationOutcome\\":\\"none\\",\\"documentationReason\\":\\"nothing durable\\",\\"evidence\\":[\\"none\\"]}"}}'
`,
    );
    chmodSync(launcher, 0o755);
    return { root, stamp, caseId, launcher, launch };
}

/** Run one real judge dispatch. */
function dispatch(stage) {
    return spawnSync(
        process.execPath,
        [
            RUNNER,
            "judge",
            "--base",
            stage.root,
            "--stamp",
            stage.stamp,
            "--case",
            stage.caseId,
            "--truth",
            join(stage.root, "truth.json"),
            "--spec",
            join(stage.root, "spec.json"),
            "--launcher",
            stage.launcher,
            "--model",
            "zai-coding-plan/test",
            "--workdir",
            join(stage.root, "runs"),
        ],
        {
            encoding: "utf8",
            env: { ...process.env, LAUNCH_CAPTURE: stage.launch },
        },
    );
}

describe("judge blinding", () => {
    it("refuses a stamp nested in judge-bound text before dispatch", () => {
        // Arrange
        const stage = judgeStage("The work mentions pd-A-r0-S02 in passing.\n");

        // Act
        const result = dispatch(stage);

        // Assert
        assert.equal(result.status, 3, result.stderr);
        assert.equal(existsSync(stage.launch), false);
    });

    it("refuses an edited final answer before dispatch", () => {
        // Arrange
        const stage = judgeStage("Nothing durable was found.\n");
        writeFileSync(
            join(stage.root, "results", stage.stamp, stage.caseId, "final.md"),
            "An answer edited after capture.\n",
        );

        // Act
        const result = dispatch(stage);

        // Assert
        assert.equal(result.status, 4, result.stderr);
        assert.match(String(result.stderr), /no longer matches/);
        assert.equal(existsSync(stage.launch), false);
    });

    it("refuses a missing answer hash without explicit legacy coverage", () => {
        // Arrange
        const stage = judgeStage("Nothing durable was found.\n", {});

        // Act
        const result = dispatch(stage);

        // Assert
        assert.equal(result.status, 4, result.stderr);
        assert.match(String(result.stderr), /no answer hash/);
        assert.equal(existsSync(stage.launch), false);
    });

    it("renders the declared lake and path in the retrieval criterion", () => {
        // Arrange
        const prompt = (
            lake: string,
            changedPaths: string[],
        ): string =>
            buildAcPrompt({
                taskPrompt: "Repair it.",
                standingPermission: "Record durable findings.",
                scenarioTruth: "truth",
                beforeDocs: [],
                afterDocs: [],
                changedPaths,
                primary: { status: "pass", exit: 0, stdout: "", stderr: "" },
                docsOperations: [],
                answer: "answer",
                retrievalSpec: {
                    note: "db/pool.md",
                    lake,
                    detail: "the pool cap",
                },
            });

        // Act
        const shared = prompt("shared", ["db/pool.md"]);
        const docs = prompt("docs", ["db/pool.md"]);

        // Assert
        assert.match(shared, /`shared\/db\/pool\.md`/);
        assert.match(shared, /declared lake "shared"/);
        assert.match(docs, /`docs\/db\/pool\.md`/);
        assert.notEqual(shared, docs);
    });

    it("dispatches from a neutral working directory", () => {
        // Arrange
        const stage = judgeStage("Nothing durable was found.\n");

        // Act
        const result = dispatch(stage);

        // Assert
        assert.equal(result.status, 0, result.stderr);
        const seen = JSON.parse(readFileSync(stage.launch, "utf8"));
        assert.ok(!seen.cwd.includes(stage.stamp));
        assert.ok(!seen.pwd.includes(stage.stamp));
        assert.equal(basename(seen.cwd), "work");
        assert.match(basename(dirname(seen.cwd)), /^[a-f0-9]{16}$/);
    });
});
